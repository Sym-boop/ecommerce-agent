def main() -> int:
    bw._load()
    words = [e.word for e in bw._ENTRIES]
    print(f"现有词条: {len(words)}")

    missing = [w for w in words if w not in CLASSIFY]
    extra = [w for w in CLASSIFY if w not in words]
    if missing:
        print(f"❌ 有 {len(missing)} 个词未分类: {missing}")
        return 1
    if extra:
        print(f"⚠️ 映射表多出 {len(extra)} 个词（词表里没有）: {extra}")

    # 检查同一分类是否只映射到一条依据
    for w, cat in CLASSIFY.items():
        if cat not in BASIS:
            print(f"❌ 未知分类 {cat}（词 {w}）")
            return 1

    lines = [HEADER.rstrip("\n")]
    for w in words:
        cat = CLASSIFY[w]
        lines.append(f"{w}|{cat}||{BASIS[cat]}")

    out = ROOT / "data" / "raw" / "forbidden_words.txt"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"✅ 已写入 {out}")
    print(f"   词条 {len(words)} 条，全部带分类与依据")
    from collections import Counter
    for cat, n in Counter(CLASSIFY.values()).most_common():
        print(f"   {cat:<6} {n:>3} 条  ← {BASIS[cat]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
